"""Generated FastAPI serving app (string template).

The generated app loads the FULL serialized pipeline (preprocessing + model as
one object), validates every request with the SAME Pandera schema built at
profiling time, and returns predictions plus calibrated probabilities. It is
emitted as source into the deployment bundle so it can be reviewed and run
standalone.
"""

from __future__ import annotations

from mlteam.contracts import TaskType

APP_SOURCE = '''"""Auto-generated by mlteam. Serves a single trained pipeline.

Run:  uvicorn serve:app --host 0.0.0.0 --port 8080
Env:  MODEL_PATH (default ./model/pipeline.joblib)
      SCHEMA_PATH (default ./model/inference_schema.json)
"""

from __future__ import annotations

import json
import os
from pathlib import Path
from typing import Any

import joblib
import pandas as pd
import pandera.pandas as pa
from fastapi import FastAPI, HTTPException
from pydantic import BaseModel

MODEL_PATH = Path(os.environ.get("MODEL_PATH", "./model/pipeline.joblib"))
SCHEMA_PATH = Path(os.environ.get("SCHEMA_PATH", "./model/inference_schema.json"))
TASK_TYPE = "{task_type}"

_KIND_DTYPE = {{"numeric": float, "categorical": object, "datetime": object}}


def _build_schema(spec: dict[str, Any]) -> pa.DataFrameSchema:
    columns = {{}}
    for entry in spec["columns"]:
        columns[entry["name"]] = pa.Column(
            _KIND_DTYPE[entry["kind"]],
            nullable=entry["nullable"],
            coerce=True,
            required=True,
        )
    return pa.DataFrameSchema(columns, strict=False)


pipeline = joblib.load(MODEL_PATH)
schema_spec = json.loads(SCHEMA_PATH.read_text())
schema = _build_schema(schema_spec)

app = FastAPI(title="mlteam model server", version="1.0")


class PredictRequest(BaseModel):
    rows: list[dict[str, Any]]


class PredictResponse(BaseModel):
    predictions: list[Any]
    probabilities: list[dict[str, float]] | None = None


@app.get("/health")
def health() -> dict[str, str]:
    return {{"status": "ok", "task_type": TASK_TYPE}}


@app.post("/predict", response_model=PredictResponse)
def predict(request: PredictRequest) -> PredictResponse:
    if not request.rows:
        raise HTTPException(status_code=422, detail="rows must be non-empty")
    frame = pd.DataFrame(request.rows)
    try:
        frame = schema.validate(frame, lazy=True)
    except pa.errors.SchemaErrors as exc:
        cases = exc.failure_cases.to_json(orient="records")
        raise HTTPException(status_code=422, detail=json.loads(cases)) from exc

    predictions = [
        _to_native(value) for value in pipeline.predict(frame)
    ]
    probabilities = None
    if hasattr(pipeline, "predict_proba"):
        classes = [str(c) for c in pipeline.classes_]
        proba = pipeline.predict_proba(frame)
        probabilities = [
            {{cls: float(p) for cls, p in zip(classes, row)}} for row in proba
        ]
    return PredictResponse(predictions=predictions, probabilities=probabilities)


def _to_native(value: Any) -> Any:
    import numpy as np

    if isinstance(value, np.generic):
        return value.item()
    return value
'''


def render_app(task_type: TaskType) -> str:
    """Return the serving app source for a given task type.

    Takes the TaskType enum (not a free string) so no attacker-controlled text
    can ever reach the format template.
    """
    return APP_SOURCE.format(task_type=TaskType(task_type).value)
