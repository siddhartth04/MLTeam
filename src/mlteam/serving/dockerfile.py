"""Dockerfile + requirements generator for a deployment bundle."""

from __future__ import annotations

# Serving-only runtime deps (kept minimal; the training stack is not needed to
# serve a pickled pipeline that already embeds its transformers).
_SERVING_REQUIREMENTS = (
    "fastapi>=0.111",
    "uvicorn>=0.30",
    "pandera>=0.20",
    "pandas>=2.2",
    "scikit-learn>=1.5",
    "joblib>=1.3",
    "numpy>=1.26",
)

_DOCKERFILE = """# Auto-generated by mlteam.
FROM python:3.11-slim

WORKDIR /app
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

COPY serve.py .
COPY model/ ./model/

EXPOSE 8080
HEALTHCHECK --interval=30s --timeout=3s CMD python -c "import urllib.request; urllib.request.urlopen('http://localhost:8080/health')"
CMD ["uvicorn", "serve:app", "--host", "0.0.0.0", "--port", "8080"]
"""


def render_dockerfile() -> str:
    return _DOCKERFILE


def render_requirements(extra: tuple[str, ...] = ()) -> str:
    lines = list(_SERVING_REQUIREMENTS) + list(extra)
    return "\n".join(lines) + "\n"
